const uint8_t *font8x8_glyph(uint8_t ch) {
    static uint8_t table[96][8];
    static int built;
    if (!built) {
        memset(table, 0, sizeof table);
        for (int g = 0; g < 95; g++)
            for (int y = 0; y < 8; y++)
                for (int x = 0; x < 8; x++)
                    if (art[g][y][x] == '#') table[g][y] |= (uint8_t)(0x80 >> x);
        built = 1;
    }
    return (ch >= 0x20 && ch < 0x7F) ? table[ch - 0x20] : table[95];   /* table[95] stays blank */
}
