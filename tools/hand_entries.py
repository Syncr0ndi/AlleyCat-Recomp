"""Routine table for the release build: every hand_XXXX in src/game/*.c, at its address.

Usage: python tools/hand_entries.py SRC_DIR OUT.c
The output contains only addresses and names (no game code or data); the release program
is built from it and the hand-written C alone, without the recompiled code."""
import re, sys
from pathlib import Path

LOAD_SEG = 0x1010            # src/pc/pc.h PC_LOAD_SEG
CODE_SEG = LOAD_SEG + 0x723

src, out = Path(sys.argv[1]), Path(sys.argv[2])
offs = set()
for f in sorted(src.glob("*.c")):
    offs |= {int(h, 16) for h in re.findall(r"^void hand_([0-9a-f]{4})\(V30 \*c\)", f.read_text(), re.M)}
lines = ["/* Generated by tools/hand_entries.py. Do not edit. */", '#include "hand.h"', ""]
lines += [f"void hand_{o:04x}(V30 *c);" for o in sorted(offs)]
lines.append("extern uint32_t cat_seq;")
for o in sorted(offs):
    lines.append(f"static void r_{o:04x}(V30 *c) {{ cat_seq++; hand_{o:04x}(c); cat_seq++; c->ip = pop16(c); }}")
lines.append("const v30_entry cat_entries[] = {")
for o in sorted(offs):
    lines.append(f"    {{0x{CODE_SEG * 16 + o:05x}, 0x{CODE_SEG:04x}, 0x{o:04x}, r_{o:04x}}},")
lines.append("};")
lines.append(f"const unsigned cat_entry_count = {len(offs)};")
text = "\n".join(lines) + "\n"
if not out.exists() or out.read_text() != text:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, newline="\n")
print(f"{len(offs)} hand-written routines -> {out}")
